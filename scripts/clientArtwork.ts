import * as fs from 'fs';
import * as path from 'path';
import sharp, {type Metadata} from 'sharp';
import type {ClientConfig} from '../src/app/config/types';

type ArtworkName = 'app-icon.png' | 'splash-logo.png' | 'brand-logo.png';
type Artwork = Record<ArtworkName, Buffer>;
type GeneratedFile = {path: string; content: string | Buffer};
const NAMES: ArtworkName[] = ['app-icon.png', 'splash-logo.png', 'brand-logo.png'];
const DENSITIES = {mdpi: 1, hdpi: 1.5, xhdpi: 2, xxhdpi: 3, xxxhdpi: 4};

function colorComponents(hex: string) {
  const value = hex.slice(1);
  const rgb: [number, number, number] = [0, 2, 4].map(index => parseInt(value.slice(index, index + 2), 16)) as [number, number, number];
  return {rgb, alpha: value.length === 8 ? parseInt(value.slice(6, 8), 16) / 255 : 1};
}

function androidColor(hex: string) {
  return hex.length === 9 ? `#${hex.slice(7)}${hex.slice(1, 7)}` : hex;
}

async function placeholderArtwork(primaryColor: string): Promise<Artwork> {
  const iconSvg = `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024"><rect width="1024" height="1024" fill="${primaryColor}"/><circle cx="512" cy="512" r="290" fill="white"/><circle cx="512" cy="512" r="145" fill="${primaryColor}"/></svg>`;
  const logoSvg = `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="1200"><circle cx="600" cy="600" r="350" fill="${primaryColor}"/><circle cx="600" cy="600" r="175" fill="white"/></svg>`;
  const [icon, logo] = await Promise.all([sharp(Buffer.from(iconSvg)).png().toBuffer(), sharp(Buffer.from(logoSvg)).png().toBuffer()]);
  return {'app-icon.png': icon, 'splash-logo.png': logo, 'brand-logo.png': logo};
}

async function validatePng(name: ArtworkName, buffer: Buffer): Promise<void> {
  let metadata: Metadata;
  try { metadata = await sharp(buffer).metadata(); }
  catch { throw new Error(`Invalid assets/${name}: the file is not a readable PNG.`); }
  if (metadata.format !== 'png' || !metadata.width || !metadata.height) throw new Error(`Invalid assets/${name}: expected a PNG image.`);
  if (name === 'app-icon.png' && (metadata.width !== 1024 || metadata.height !== 1024)) throw new Error('Invalid assets/app-icon.png: expected exactly 1024 x 1024 pixels.');
  if (name === 'splash-logo.png' && (metadata.width < 1200 || metadata.height < 1200)) throw new Error('Invalid assets/splash-logo.png: expected at least 1200 x 1200 pixels.');
  if (name === 'brand-logo.png' && metadata.width < 512) throw new Error('Invalid assets/brand-logo.png: expected at least 512 pixels wide.');
  const stats = await sharp(buffer).ensureAlpha().stats();
  const alpha = stats.channels[3];
  if (!alpha) throw new Error(`Invalid assets/${name}: could not inspect transparency.`);
  if (name === 'app-icon.png' && alpha.min !== 255) throw new Error('Invalid assets/app-icon.png: the icon must be fully opaque.');
  if (name !== 'app-icon.png' && alpha.min === 255) throw new Error(`Invalid assets/${name}: expected a transparent background.`);
  if (name !== 'app-icon.png' && alpha.max === 0) throw new Error(`Invalid assets/${name}: the image is completely transparent.`);
}

export async function loadClientArtwork(clientDirectory: string, environment: 'development' | 'production', primaryColor: string): Promise<Artwork> {
  const assetDirectory = path.join(clientDirectory, 'assets');
  const present = NAMES.filter(name => fs.existsSync(path.join(assetDirectory, name)));
  if (present.length === 0 && environment === 'development') return placeholderArtwork(primaryColor);
  for (const name of NAMES) if (!present.includes(name)) throw new Error(`Missing assets/${name} for ${environment} client artwork.`);
  const artwork = Object.fromEntries(NAMES.map(name => [name, fs.readFileSync(path.join(assetDirectory, name))])) as Artwork;
  for (const name of NAMES) await validatePng(name, artwork[name]);
  return artwork;
}

function iosIconSlots() {
  const slots: Array<{idiom: string; size: number; scale: number}> = [];
  for (const size of [20, 29, 40, 60]) for (const scale of [2, 3]) slots.push({idiom: 'iphone', size, scale});
  for (const size of [20, 29, 40, 76]) for (const scale of [1, 2]) slots.push({idiom: 'ipad', size, scale});
  slots.push({idiom: 'ipad', size: 83.5, scale: 2});
  slots.push({idiom: 'ios-marketing', size: 1024, scale: 1});
  return slots;
}

function launchStoryboard(background: string): string {
  const {rgb, alpha} = colorComponents(background);
  const component = (value: number) => (value / 255).toFixed(6);
  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- AUTO-GENERATED by client:prepare. DO NOT EDIT. -->
<document type="com.apple.InterfaceBuilder3.CocoaTouch.Storyboard.XIB" version="3.0" toolsVersion="15702" targetRuntime="iOS.CocoaTouch" propertyAccessControl="none" useAutolayout="YES" launchScreen="YES" useSafeAreas="YES" initialViewController="launch-controller">
  <scenes>
    <scene sceneID="launch-scene">
      <objects>
        <viewController id="launch-controller" sceneMemberID="viewController">
          <view key="view" contentMode="scaleToFill" id="launch-view">
            <rect key="frame" x="0" y="0" width="375" height="667"/>
            <subviews>
              <imageView userInteractionEnabled="NO" contentMode="scaleAspectFit" image="ClientLaunchLogo" translatesAutoresizingMaskIntoConstraints="NO" id="launch-logo">
                <rect key="frame" x="77" y="223" width="220" height="220"/>
              </imageView>
            </subviews>
            <color key="backgroundColor" red="${component(rgb[0])}" green="${component(rgb[1])}" blue="${component(rgb[2])}" alpha="${alpha.toFixed(6)}" colorSpace="custom" customColorSpace="sRGB"/>
            <constraints>
              <constraint firstItem="launch-logo" firstAttribute="centerX" secondItem="launch-view" secondAttribute="centerX" id="logo-center-x"/>
              <constraint firstItem="launch-logo" firstAttribute="centerY" secondItem="launch-view" secondAttribute="centerY" id="logo-center-y"/>
              <constraint firstItem="launch-logo" firstAttribute="width" constant="220" id="logo-width"/>
              <constraint firstItem="launch-logo" firstAttribute="height" constant="220" id="logo-height"/>
            </constraints>
          </view>
        </viewController>
      </objects>
    </scene>
  </scenes>
  <resources><image name="ClientLaunchLogo" width="220" height="220"/></resources>
</document>
`;
}

export async function buildClientArtworkFiles(workspaceRoot: string, clientId: string, environment: 'development' | 'production', branding: ClientConfig['branding']): Promise<GeneratedFile[]> {
  const artwork = await loadClientArtwork(path.join(workspaceRoot, 'clients', clientId), environment, branding.primaryColor);
  const files: GeneratedFile[] = [];
  const androidRes = path.join(workspaceRoot, 'android', 'app', 'src', 'main', 'res');
  for (const [density, scale] of Object.entries(DENSITIES)) {
    const iconSize = Math.round(48 * scale);
    const splashSize = Math.round(288 * scale);
    const icon = await sharp(artwork['app-icon.png']).resize(iconSize, iconSize).removeAlpha().toColourspace('srgb').png().toBuffer();
    const circle = Buffer.from(`<svg width="${iconSize}" height="${iconSize}"><circle cx="${iconSize / 2}" cy="${iconSize / 2}" r="${iconSize / 2}" fill="white"/></svg>`);
    files.push({path: path.join(androidRes, `mipmap-${density}`, 'client_launcher.png'), content: icon});
    files.push({path: path.join(androidRes, `mipmap-${density}`, 'client_launcher_round.png'), content: await sharp(icon).ensureAlpha().composite([{input: circle, blend: 'dest-in'}]).png().toBuffer()});
    files.push({path: path.join(androidRes, `drawable-${density}`, 'client_splash_logo.png'), content: await sharp(artwork['splash-logo.png']).resize(splashSize, splashSize, {fit: 'contain', background: '#00000000'}).toColourspace('srgb').png().toBuffer()});
  }
  files.push({path: path.join(androidRes, 'values', 'client_artwork_colors.xml'), content: `<?xml version="1.0" encoding="utf-8"?>\n<!-- AUTO-GENERATED by client:prepare. DO NOT EDIT. -->\n<resources><color name="client_splash_background">${androidColor(branding.backgroundColor)}</color></resources>\n`});

  const ios = path.join(workspaceRoot, 'ios', 'WhiteLabelApp');
  const iconSet = path.join(ios, 'Images.xcassets', 'ClientAppIcon.appiconset');
  const icons = [];
  for (const slot of iosIconSlots()) {
    const filename = `icon-${slot.idiom}-${String(slot.size).replace('.', '_')}@${slot.scale}x.png`;
    const pixels = Math.round(slot.size * slot.scale);
    files.push({path: path.join(iconSet, filename), content: await sharp(artwork['app-icon.png']).resize(pixels, pixels).removeAlpha().toColourspace('srgb').png().toBuffer()});
    icons.push({filename, idiom: slot.idiom, size: `${slot.size}x${slot.size}`, scale: `${slot.scale}x`});
  }
  files.push({path: path.join(iconSet, 'Contents.json'), content: JSON.stringify({images: icons, info: {author: 'xcode', version: 1}}, null, 2) + '\n'});
  const logoSet = path.join(ios, 'Images.xcassets', 'ClientLaunchLogo.imageset');
  const logos = [];
  for (const scale of [1, 2, 3]) {
    const filename = `launch-logo@${scale}x.png`;
    files.push({path: path.join(logoSet, filename), content: await sharp(artwork['splash-logo.png']).resize(220 * scale, 220 * scale, {fit: 'contain', background: '#00000000'}).toColourspace('srgb').png().toBuffer()});
    logos.push({filename, idiom: 'universal', scale: `${scale}x`});
  }
  files.push({path: path.join(logoSet, 'Contents.json'), content: JSON.stringify({images: logos, info: {author: 'xcode', version: 1}}, null, 2) + '\n'});
  files.push({path: path.join(ios, 'ClientLaunchScreen.storyboard'), content: launchStoryboard(branding.backgroundColor)});
  files.push({path: path.join(workspaceRoot, 'src', 'generated', 'brand-logo.png'), content: await sharp(artwork['brand-logo.png']).toColourspace('srgb').png().toBuffer()});
  return files;
}
